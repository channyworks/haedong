"""Build the historical data script used by the offline-capable preview."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
NAMES = ("characters", "factions", "scenarios")
DATA = ROOT / "data/history"
BUNDLE = ROOT / "scenario-preview/history-data.js"


def bundle():
    records = {name: json.loads((DATA / f"{name}.json").read_text(encoding="utf-8")) for name in NAMES}
    lines = ['"use strict";', '// Generated by scripts/build_history.py from data/history.', 'window.haedongHistoryData = {']
    for name, dataset in records.items():
        if isinstance(dataset, list):
            lines.append(f"  {name}: [")
            lines.extend("    " + json.dumps(record, ensure_ascii=False) + "," for record in dataset)
            lines.append("  ],")
        else:
            lines.append(f"  {name}: {{")
            for key, value in dataset.items():
                lines.append(f"    {key}: {json.dumps(value, ensure_ascii=False)},")
            lines.append("  },")
    return "\n".join(lines + ['};', ''])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = bundle()
    if args.check:
        if not BUNDLE.is_file() or BUNDLE.read_text(encoding="utf-8") != output:
            parser.exit(1, "History bundle is outdated. Run python scripts/build_history.py.\n")
    else:
        BUNDLE.write_text(output, encoding="utf-8", newline="\n")
